def make_request(site: Path, **overrides) -> IngestRequest:
    fields = {
        "source": FIXTURE,
        "site": site,
        "channel": Channel.MAIN,
        "product_version": "2.1.0",
        "source_ref": "main",
        "source_sha": "abc123",
        **overrides,
    }
    return IngestRequest(**fields)


@pytest.fixture
def site(tmp_path: Path) -> Path:
    site = tmp_path / "website"
    site.mkdir()

    (site / "docs").mkdir()
    (site / "sidebars.ts").write_text("", encoding="utf-8", newline="\n")
    (site / "sync-state.json").write_text(
        render_sync_state(EMPTY_STATE), encoding="utf-8", newline="\n"
    )
    (site / "versions.json").write_text("[]\n", encoding="utf-8", newline="\n")

    return site


def published_bytes(site: Path) -> dict[PurePosixPath, bytes]:
    """Return ``{path: content}`` for every page under docs/ plus sidebars.ts."""
    files = {
        PurePosixPath(p.relative_to(site).as_posix()): p.read_bytes()
        for p in (site / "docs").rglob("*")
        if p.is_file()
    }
    files[PurePosixPath("sidebars.ts")] = (site / "sidebars.ts").read_bytes()

    return files


def test_build_plan_reports_mdx_unsafe_prose_with_path_and_line(tmp_path):
    source = tmp_path / "source"
    shutil.copytree(FIXTURE, source)
    guide = source / "docs" / "users" / "guide.md"
    lines = guide.read_text(encoding="utf-8").splitlines(keepends=True)
    guide.write_text("".join(lines) + "Set ${HARBOR_HOME} first.\n", encoding="utf-8")
    bad_line = len(lines) + 1

    with pytest.raises(ValueError) as excinfo:
        build_plan(make_request(tmp_path / "site", source=source))

    message = str(excinfo.value)
    assert message.startswith("MDX-unsafe content in source docs:")
    assert f"docs/users/guide.md:{bad_line}: stray '{{' in prose" in message


def test_build_plan_reports_package_readme_line_as_in_source(tmp_path):
    """Bridged package pages get a facts table prepended; line numbers must ignore it."""
    source = tmp_path / "source"
    shutil.copytree(FIXTURE, source)
    readme = source / "packages" / "demo" / "README.md"
    lines = readme.read_text(encoding="utf-8").splitlines(keepends=True)
    readme.write_text("".join(lines) + "Needs x <= 3.\n", encoding="utf-8")
    bad_line = len(lines) + 1

    with pytest.raises(ValueError) as excinfo:
        build_plan(make_request(tmp_path / "site", source=source))

    assert str(excinfo.value).splitlines()[1:] == [
        f"- packages/demo/README.md:{bad_line}: unexpected '<' in prose"
    ]


def test_build_plan_fixture_file_set_and_sidebar(tmp_path):
    plan = build_plan(make_request(tmp_path / "site"))

    assert sorted(plan.pages) == EXPECTED_PAGES
    assert plan.sidebars_ts == EXPECTED_SIDEBARS_TS
    for path, content in plan.pages.items():
        assert "source_sha" not in content, path
        assert "source_ref" not in content, path
        assert "sidebar_position" not in content, path


def test_new_sha_same_content_rewrites_nothing(site):
    """A new upstream sha with identical docs must not touch any published file."""
    assert ingest.run(make_request(site, source_sha="abc123")) is WriteOutcome.WRITTEN
    before = published_bytes(site)

    assert ingest.run(make_request(site, source_sha="def456")) is WriteOutcome.NO_CHANGES
    assert published_bytes(site) == before
